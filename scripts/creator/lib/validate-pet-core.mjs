/**
 * Creator pet validation core (V8 CTR-038; R2/R3/R7 fix round).
 * Pure ESM shared by the `pnpm pet:validate` CLI and the contract tests.
 *
 * A creator pet directory is DATA ONLY:
 *
 *   <dir>/pet/pet.json          presentation data (ajv: pet-presentation-v1)
 *   <dir>/pet/levels.json       grade descriptions per level id
 *   <dir>/pet/speech.json       bilingual speech catalog
 *   <dir>/pet/assets/           pose images (pose-N.png + .webp pairs), optional insignia SVGs
 *   <dir>/journey/manifest.json Engine Pet Pack manifest (REAL engine validatePack)
 *   <dir>/journey/assets/       journey art referenced by the manifest
 *   <dir>/LICENSE               license statement (non-empty)
 *
 * There is no definition.ts for creators: executable wiring is generated by
 * the repository's tooling from this data. Every failure names the exact
 * file and field; malformed types are rejected, never silently accepted.
 */

import { readFile, readdir, stat } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'

const require = createRequire(import.meta.url)
const Ajv = require('ajv').default
const ajvFormats = require('ajv-formats')

const SPEECH_CATEGORIES = [
  'idle', 'working', 'needs-input', 'completed', 'failed', 'milestone', 'petting', 'welcome', 'ritual',
]
const CORE_SESSION_CATEGORIES = ['idle', 'working', 'needs-input', 'completed', 'failed', 'milestone']
const THIRD_PARTY_BRANDS = ['Pony.ai', 'pony.ai']
const BAKED_NUMERAL_PATTERN = />\s*L\s*\d+\s*</
const EXPRESSION_VARIANTS = [
  'idle', 'idle-happy', 'idle-curious', 'idle-sleepy', 'working',
  'needs-input', 'completed', 'completed-proud', 'failed', 'cancelled',
]

async function fileExists(target) {
  try {
    return (await stat(target)).isFile()
  } catch {
    return false
  }
}

async function readJson(file, errors, label) {
  try {
    return JSON.parse(await readFile(file, 'utf8'))
  } catch (error) {
    errors.push(`${label} is not valid JSON: ${error.message}`)
    return undefined
  }
}

function isPlainObject(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

/**
 * Validate one creator pet directory. Returns { ok, errors } where every
 * error is a human-readable string pointing at an exact file/field.
 */
export async function validateCreatorPet(petDir, options = {}) {
  const errors = []
  const repoRoot = options.repoRoot ?? path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../..')
  const petDirPath = path.join(petDir, 'pet')
  const journeyDir = path.join(petDir, 'journey')

  // 1. Layout — all required files must exist.
  const required = ['pet/pet.json', 'pet/levels.json', 'pet/speech.json', 'journey/manifest.json', 'LICENSE']
  for (const relative of required) {
    if (!(await fileExists(path.join(petDir, relative)))) {
      errors.push(`missing required file: ${relative}`)
    }
  }
  if (errors.length > 0) return { ok: false, errors }

  // 2. LICENSE must carry content.
  const licenseText = (await readFile(path.join(petDir, 'LICENSE'), 'utf8')).trim()
  if (licenseText.length === 0) errors.push('LICENSE is empty — replace the template with your own license statement')

  // 3. pet.json — ajv schema (unknown fields rejected) + semantic checks.
  const pet = await readJson(path.join(petDirPath, 'pet.json'), errors, 'pet/pet.json')
  if (pet !== undefined) {
    const schema = options.petSchema ?? JSON.parse(await readFile(path.join(repoRoot, 'src/dsh/client/pets/pet-presentation-v1.schema.json'), 'utf8'))
    const compile = options.compilePetSchema ?? (() => {
      const ajv = new Ajv({ allErrors: true, strict: false })
      ajvFormats(ajv)
      return ajv.compile(schema)
    })()
    if (!compile(pet)) {
      for (const e of compile.errors ?? []) {
        errors.push(`pet/pet.json ${e.instancePath || '/'} ${e.message ?? 'failed schema validation'}${e.params?.additionalProperty !== undefined ? ` (offending field: ${String(e.params.additionalProperty)})` : ''}`)
      }
    } else {
      if (pet.id !== path.basename(petDir) && pet.id !== 'my-pet') {
        errors.push(`pet/pet.json id '${pet.id}' should match the pet directory name '${path.basename(petDir)}'`)
      }
      if (['vehicle', 'companion'].includes(pet.id)) {
        errors.push(`pet/pet.json id '${pet.id}' collides with a bundled reference pet; pick a distinct id`)
      }
      if (pet.recipe === 'pose-sprite' && pet.poseSprite === undefined) {
        errors.push("pet/pet.json recipe 'pose-sprite' requires a poseSprite block")
      }
      if (pet.recipe === 'engine-scene' && pet.engineScene === undefined) {
        errors.push("pet/pet.json recipe 'engine-scene' requires an engineScene block with expressionAnchors")
      }
      if (pet.gradePolicy.insigniaMode === 'overlay') {
        errors.push("pet/pet.json gradePolicy.insigniaMode 'overlay' is not implemented in the current renderer (V8 CTR-040 vocabulary; creator kit V1 supports 'none' | 'wearable')")
      }
      if (pet.gradePolicy.insigniaMode === 'wearable' && pet.poseSprite?.insignia === undefined) {
        errors.push("pet/pet.json gradePolicy.insigniaMode 'wearable' requires poseSprite.insignia with an assetSource")
      }
      if (pet.poseSprite?.insignia !== undefined && pet.gradePolicy.insigniaMode !== 'wearable') {
        errors.push("pet/pet.json poseSprite.insignia is only used when gradePolicy.insigniaMode is 'wearable'")
      }
      for (const field of ['license', 'attribution', 'provenance']) {
        if (typeof pet.license?.[field] !== 'string' || pet.license[field].trim().length === 0) {
          errors.push(`pet/pet.json license.${field} must be a non-empty string`)
        }
      }
      if (typeof pet.license?.provenance === 'string' && pet.license.provenance.length > 0
        && !(await fileExists(path.join(petDirPath, pet.license.provenance)))) {
        errors.push(`pet/pet.json license.provenance '${pet.license.provenance}' does not exist in the pet directory`)
      }
    }
  }

  // 4. levels.json — non-empty array of unique, well-formed level rows.
  const levels = await readJson(path.join(petDirPath, 'levels.json'), errors, 'pet/levels.json')
  if (levels !== undefined) {
    if (!Array.isArray(levels) || levels.length === 0) {
      errors.push('pet/levels.json must be a non-empty array of level descriptions')
    } else {
      const seen = new Set()
      levels.forEach((level, index) => {
        if (!isPlainObject(level)) {
          errors.push(`pet/levels.json /${index} must be an object`)
          return
        }
        if (typeof level.id !== 'string' || !/^l\d+$/.test(level.id)) {
          errors.push(`pet/levels.json /${index}/id must match /^l\\d+$/ (got ${JSON.stringify(level.id)})`)
        } else if (seen.has(level.id)) {
          errors.push(`pet/levels.json duplicate level id ${level.id} (/${index})`)
        } else {
          seen.add(level.id)
        }
        for (const locale of ['zh-CN', 'en']) {
          if (typeof level[locale] !== 'string' || level[locale].trim().length === 0) {
            errors.push(`pet/levels.json /${index}/${locale} must be a non-empty localized description`)
          }
        }
      })
    }
  }

  // 5. speech.json — plain object of category → bilingual line arrays.
  const speech = await readJson(path.join(petDirPath, 'speech.json'), errors, 'pet/speech.json')
  if (speech !== undefined) {
    if (!isPlainObject(speech)) {
      errors.push('pet/speech.json must be an object mapping speech categories to line arrays')
    } else {
      for (const [category, lines] of Object.entries(speech)) {
        if (!SPEECH_CATEGORIES.includes(category)) {
          errors.push(`pet/speech.json /${category} is not a known speech category (allowed: ${SPEECH_CATEGORIES.join(', ')})`)
          continue
        }
        if (!Array.isArray(lines) || lines.length === 0) {
          errors.push(`pet/speech.json /${category} must be a non-empty array of bilingual lines`)
          continue
        }
        lines.forEach((line, index) => {
          if (!isPlainObject(line)) {
            errors.push(`pet/speech.json /${category}/${index} must be an object`)
            return
          }
          for (const locale of ['zh-CN', 'en']) {
            if (typeof line[locale] !== 'string' || line[locale].trim().length === 0) {
              errors.push(`pet/speech.json /${category}/${index}/${locale} must be a non-empty string`)
            }
          }
        })
      }
      for (const category of CORE_SESSION_CATEGORIES) {
        if (!Array.isArray(speech[category]) || speech[category].length < 1) {
          errors.push(`pet/speech.json /${category} must have at least 1 line (V8 CTR-018 floor for new pets)`)
        }
      }
    }
  }

  // 6. Pose assets — pairs present, variant indices in range, SVG hygiene.
  if (pet?.poseSprite !== undefined && pet.poseSprite.poseSource?.kind === 'files') {
    const assetsDir = path.join(petDirPath, pet.poseSprite.poseSource.dir.replace(/^\.\//, ''))
    if (!existsSync(assetsDir)) {
      errors.push(`pet/${pet.poseSprite.poseSource.dir}/ does not exist — pose images are required for pose-sprite pets`)
    } else {
      const all = await readdir(assetsDir)
      const pngs = all.filter((n) => /^pose-\d+\.png$/.test(n))
      const webps = all.filter((n) => /^pose-\d+\.webp$/.test(n))
      if (pngs.length === 0) {
        errors.push('pet/assets must contain at least one pose-N.png (with its pose-N.webp twin)')
      } else if (pngs.length !== webps.length) {
        errors.push(`pet/assets pose pairs incomplete: ${pngs.length} png vs ${webps.length} webp`)
      }
      const poseCount = pngs.length
      for (const variant of EXPRESSION_VARIANTS) {
        const index = pet.poseSprite.variantPose?.[variant]
        if (typeof index !== 'number') {
          errors.push(`pet/pet.json poseSprite.variantPose.${variant} must map to a pose index`)
        } else if (index < 0 || index >= poseCount) {
          errors.push(`pet/pet.json poseSprite.variantPose.${variant} = ${index} is out of range (found ${poseCount} pose images)`)
        }
      }
    }
  }
  const assetDir = path.join(petDirPath, 'assets')
  if (existsSync(assetDir)) {
    for (const name of (await readdir(assetDir)).filter((name) => name.endsWith('.svg'))) {
      const content = await readFile(path.join(assetDir, name), 'utf8')
      if (BAKED_NUMERAL_PATTERN.test(content)) {
        errors.push(`pet/assets/${name} contains a visible baked level numeral (V8 CTR-042)`)
      }
      for (const brand of THIRD_PARTY_BRANDS) {
        if (content.includes(brand)) errors.push(`pet/assets/${name} contains third-party brand "${brand}" (V8 CTR-042)`)
      }
    }
  }

  // 7. Journey — the REAL engine validator (ajv schema + semantic rules).
  const manifest = await readJson(path.join(journeyDir, 'manifest.json'), errors, 'journey/manifest.json')
  if (manifest !== undefined && pet !== undefined) {
    if (pet.packId !== manifest.packId) {
      errors.push(`pet/pet.json packId '${pet.packId}' must equal journey/manifest.json packId '${manifest.packId}'`)
    }
    // Detailed schema pass (names the offending field) alongside the engine
    // validator below (the semantic authority: thresholds, refs, twins).
    const manifestSchema = options.manifestSchema ?? JSON.parse(await readFile(path.join(repoRoot, 'src/engine/schema/pet-pack-manifest-v1.schema.json'), 'utf8'))
    const compileManifest = options.compileManifestSchema ?? (() => {
      const ajv = new Ajv({ allErrors: true, strict: false })
      ajvFormats(ajv)
      return ajv.compile(manifestSchema)
    })()
    if (!compileManifest(manifest)) {
      for (const e of compileManifest.errors ?? []) {
        errors.push(`journey/manifest.json ${e.instancePath || '/'} ${e.message ?? 'failed schema validation'}${e.params?.additionalProperty !== undefined ? ` (offending field: ${String(e.params.additionalProperty)})` : ''}`)
      }
    }
    const { ensureEngineBundle } = await import('./engine-validate.mjs')
    const engine = options.engine ?? (await ensureEngineBundle())
    const result = engine.validatePack(manifest, {
      resolveAssetUrl: (assetPath) => (existsSync(path.join(journeyDir, assetPath)) ? path.join(journeyDir, assetPath) : undefined),
      requireBundledKeepsakes: true,
    })
    if (!result.ok) {
      for (const message of result.errors ?? ['journey manifest rejected by the engine validator']) {
        errors.push(`journey/manifest.json: ${String(message).replace(path.join(journeyDir, ''), '')}`)
      }
    }
  }

  // 8. Brand hygiene on the creator's own text files (CTR-039).
  for (const relative of ['pet/pet.json', 'pet/levels.json', 'pet/speech.json', 'journey/manifest.json', 'LICENSE']) {
    const content = await readFile(path.join(petDir, relative), 'utf8')
    for (const brand of THIRD_PARTY_BRANDS) {
      if (content.includes(brand)) errors.push(`${relative} contains third-party brand "${brand}" (V8 CTR-039)`)
    }
  }

  return { ok: errors.length === 0, errors }
}
